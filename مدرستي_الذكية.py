# إنشاء فهرس الكتب
catalog = []
for grade_num in range(5, 13):
    for term_num in range(1, 4):
        for subject in subjects:
            catalog.append({
                "الصف": f"الصف {grade_num}",
                "الفصل": f"الفصل {term_num}",
                "المادة": subject,
                "اسم الكتاب": "",
                "رابط الكتاب": ""
            })

catalog_path = os.path.join(LIBRARY_DIR, "فهرس_الكتب.json")
with open(catalog_path, "w", encoding="utf-8") as f:
    json.dump(catalog, f, ensure_ascii=False, indent=2)

def search_books(grade, term, subject, keyword):
    results = []
    for item in catalog:
        if item["الصف"] != grade or item["الفصل"] != term:
            continue
        if subject != "كل المواد" and item["المادة"] != subject:
            continue
        results.append(
            f"📘 {item['المادة']}\n"
            f"الصف: {item['الصف']} — {item['الفصل']}\n"
            "لم يُضف ملف الكتاب بعد؛ سنربط الكتب الفعلية في الخطوة التالية."
        )

    if keyword.strip():
        results = [
            r for r in results
            if keyword.strip().lower() in r.lower()
        ]

    return "\n\n".join(results) or "لا توجد نتائج مطابقة."


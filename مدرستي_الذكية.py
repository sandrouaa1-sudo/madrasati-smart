def game_status(game):
    if not game or "started" not in game:
        return "اللعبة اختيارية — مدتها 15 دقيقة."

    remaining = max(0, 900 - int(time.time() - game["started"]))
    if remaining <= 0:
        return f"⏰ انتهى وقت اللعب! نتيجتك: {game['score']}"

    return f"⏱️ الوقت المتبقي: {remaining // 60:02d}:{remaining % 60:02d}"



def start_game():
    order = list(range(len(PUZZLES)))
    random.shuffle(order)
    return {
        "started": time.time(),
        "order": order,
        "index": 0,
        "score": 0
    }, "بدأ التحدي! لديكِ 15 دقيقة 🧠", gr.update(
        choices=PUZZLES[order[0]][1],
        value=None
    ), PUZZLES[order[0]][0]


def game_question(game, answer):
    if not game or "started" not in game:
        return game, "اضغطي «ابدئي اللعب» أولًا.", gr.update(), ""

    elapsed = time.time() - game["started"]
    if elapsed >= 900:
        return game, f"⏰ انتهى وقت اللعب! نتيجتك: {game['score']}", gr.update(), ""

    if not answer:
        i = game["order"][game["index"]]
        return game, "اختاري إجابة أولًا.", gr.update(
            choices=PUZZLES[i][1], value=None
        ), PUZZLES[i][0]

    i = game["order"][game["index"]]
    if answer == PUZZLES[i][2]:
        game["score"] += 1

    game["index"] += 1

    if game["index"] >= len(game["order"]):
        return game, f"🎉 انتهى التحدي! نتيجتك: {game['score']} من {len(game['order'])}", gr.update(), ""

    next_i = game["order"][game["index"]]
    return game, f"أحسنتِ! نتيجتك الحالية: {game['score']}", gr.update(
        choices=PUZZLES[next_i][1], value=None
    ), PUZZLES[next_i][0]


